def command_help(command, *, admin=False, root=False):
    command = command.lower().lstrip('/').split('@', 1)[0]
    sections = [PUBLIC_HELP]
    if admin or root:
        sections.append(ADMIN_HELP)
    if root:
        sections.append(ROOT_HELP)
    for section in sections:
        for aliases, text in section.items():
            if command in aliases:
                return text
    return 'Команда не найдена или недоступна. Список команд: /help.'


